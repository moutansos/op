// Package systemd renders and locates the op serve systemd user unit.
package systemd

import (
	"os"
	"path/filepath"
	"strings"
)

// UnitName is the user unit managed by op service.
const UnitName = "op.service"

// UnitSpec describes the op serve invocation a unit runs.
type UnitSpec struct {
	Executable string
	ConfigPath string
	// Path is the PATH the service runs with, so git, tmux, shells, and editors resolve.
	Path string
}

// RenderUnit returns the unit file contents for spec.
func RenderUnit(spec UnitSpec) string {
	command := []string{quote(spec.Executable, true)}
	if spec.ConfigPath != "" {
		command = append(command, "--config", quote(spec.ConfigPath, true))
	}
	command = append(command, "serve")
	var builder strings.Builder
	builder.WriteString(`# Generated by "op service install". Rerun it after moving op or its config.
[Unit]
Description=op remote-control API
Documentation=https://github.com/moutansos/op#server-and-remote-client

[Service]
Type=simple
`)
	if spec.Path != "" {
		builder.WriteString("Environment=" + quote("PATH="+spec.Path, false) + "\n")
	}
	builder.WriteString("ExecStart=" + strings.Join(command, " ") + `
Restart=on-failure
RestartSec=5s
UMask=0077
NoNewPrivileges=true

[Install]
WantedBy=default.target
`)
	return builder.String()
}

// quote escapes value for a unit file. Specifiers (%) are expanded in every
// setting, while $ is only expanded in command lines.
func quote(value string, command bool) string {
	escaped := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "%", "%%").Replace(value)
	if command {
		escaped = strings.ReplaceAll(escaped, "$", "$$")
	}
	if escaped == value && value != "" && !strings.ContainsAny(value, " \t\n'\";") {
		return value
	}
	return `"` + escaped + `"`
}

// UserUnitDir returns the directory systemd reads user units from.
func UserUnitDir(lookupEnv func(string) string) (string, error) {
	if root := lookupEnv("XDG_CONFIG_HOME"); filepath.IsAbs(root) {
		return filepath.Join(root, "systemd", "user"), nil
	}
	home := lookupEnv("HOME")
	if home == "" {
		var err error
		if home, err = os.UserHomeDir(); err != nil {
			return "", err
		}
	}
	return filepath.Join(home, ".config", "systemd", "user"), nil
}

// Booted reports whether systemd is the running init system.
func Booted() bool {
	info, err := os.Stat("/run/systemd/system")
	return err == nil && info.IsDir()
}
